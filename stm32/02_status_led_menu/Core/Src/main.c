//******** ISR ********
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
	if(on)
	{
		if(htim->Instance==TIM2)
		{
			if(connecting) //100ms blinking
			{
				HAL_GPIO_TogglePin(LED_B_GPIO_Port, LED_B_Pin);
			}
			if(normal)		//500ms blinking
			{
				if(cnt==4)
				{
					cnt=0;
					HAL_GPIO_TogglePin(LED_B_GPIO_Port, LED_B_Pin);
				}
				cnt++;
			}
		}
		if(htim->Instance==TIM4)
		{	//RED LED PWM - Danger
			if(danger && (!normal))
			{
				__HAL_TIM_SET_COMPARE(&htim12, TIM_CHANNEL_1, pwm_red);
				pwm_red+=5;
			}
		}
	}
}
